# ── PII anonymisation ─────────────────────────────────────────────────────────
_PII = [
    (re.compile(r"\b[\w.+-]+@[\w-]+\.[a-z]{2,}\b", re.I), "[EMAIL]"),
    (re.compile(r"\b(\+92|0)?3\d{2}[-.\s]?\d{7}\b"),       "[PHONE]"),
    (re.compile(r"\b\d{13}\b"),                            "[CNIC]"),
]
def anonymize(t):
    for p, r in _PII:
        t = p.sub(r, t)
    return t

def clean(text):
    if not isinstance(text, str): return ""
    text = text.lower()
    text = re.sub(r"http\S+|www\.\S+", " ", text)
    text = re.sub(r"[^\w\s.,!?;:()\-']", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return anonymize(text)

# ── Missing-value handler ─────────────────────────────────────────────────────
def handle_missing(df, qc, ac):
    before = len(df)
    df = df[~(df[qc].isna() & df[ac].isna())].copy()
    df[qc] = df[qc].fillna("[QUESTION UNAVAILABLE]")
    df[ac] = df[ac].fillna("[ANSWER UNAVAILABLE]")
    df = df.drop_duplicates(subset=[qc])
    df = df[(df[qc].str.len() >= 5) & (df[ac].str.len() >= 5)]
    print(f"   Rows: {before} → {len(df)} (missing/noise removed)")
    return df

# ── Load Dataset 1 (FAQ) ──────────────────────────────────────────────────────
def load_faq(path):
    if not os.path.exists(path):
        raise FileNotFoundError(f"Dataset 1 not found: {path}")
    df   = pd.read_csv(path)
    cols = [c.lower().strip() for c in df.columns]
    qc   = df.columns[cols.index("question")] if "question" in cols else df.columns[0]
    ac   = df.columns[cols.index("answer")]   if "answer"   in cols else df.columns[1]
    df   = df[[qc, ac]].astype(str)
    df   = handle_missing(df, qc, ac)
    df[qc] = df[qc].apply(clean)
    df[ac] = df[ac].apply(clean)
    df = df[(df[qc].str.len() >= 5) & (df[ac].str.len() >= 5)]
    return df, qc, ac

