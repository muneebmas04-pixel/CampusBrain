# ── Chunking & Ingestion ──────────────────────────────────────────────────────
def split_sentences(text):
    text = re.sub(r"\n{2,}", "\n\n", text)
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+(?=[A-Z])", text) if s.strip()]

def chunk(text, max_chars=700, overlap=2):
    sents = split_sentences(text)
    chunks, cur, cur_len = [], [], 0
    for s in sents:
        if cur_len + len(s) > max_chars and cur:
            chunks.append(" ".join(cur))
            cur = cur[-overlap:]; cur_len = sum(len(x) for x in cur)
        cur.append(s); cur_len += len(s)
    if cur: chunks.append(" ".join(cur))
    return chunks

def ingest_document(text, doc_name):
    text = anonymize(text)
    clist = chunk(text)
    docs, metas, ids = [], [], []
    for i, c in enumerate(clist):
        docs.append(c)
        metas.append({"source": doc_name, "chunk_index": i, "dataset": "upload"})
        ids.append(f"{doc_name}__{i}")
    try: collection.delete(ids=ids)
    except: pass
    collection.add(documents=docs, metadatas=metas, ids=ids)
    ingested_docs.append({"name": doc_name, "chunks": len(clist),
                           "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M")})
    return len(clist)

def load_pdf(path):
    r = PdfReader(path)
    return "\n\n".join(p.extract_text() or "" for p in r.pages)

# ── Retrieval ─────────────────────────────────────────────────────────────────
DIST_THRESH = 1.5

def retrieve(query, n=8):
    if collection.count() == 0: return "", [], False, 0.0
    res   = collection.query(query_texts=[query], n_results=min(n, collection.count()),
                             include=["documents","metadatas","distances"])
    docs  = res["documents"][0] if res["documents"] else []
    metas = res["metadatas"][0]  if res["metadatas"]  else []
    dists = res["distances"][0]  if res["distances"]  else []
    good, sources, best = [], [], float("inf")
    for doc, meta, dist in zip(docs, metas, dists):
        if dist < DIST_THRESH:
            good.append(doc); best = min(best, dist)
            src = meta.get("source","Unknown")
            if src not in sources: sources.append(src)
    is_conf    = len(good) > 0
    conf_score = max(0.0, round((1 - best/DIST_THRESH)*100, 1)) if is_conf else 0.0
    return "\n\n---\n\n".join(good), sources, is_conf, conf_score

# ── Local Fallback ────────────────────────────────────────────────────────────
def local_answer_from_context(question, context, sources):
    if not context.strip():
        return ("ℹ️ I couldn't find specific information for your question.\n\n"
                "Please visit **[neduet.edu.pk](https://www.neduet.edu.pk)** or contact "
                "the relevant department directly.")
    stop = {"what","does","the","and","for","how","are","that","this",
            "can","with","have","from","not","you","your","about","will"}
    q_words = set(re.findall(r'\b[a-z]{3,}\b', question.lower())) - stop
    sentences = []
    for chunk_text in context.split("---"):
        for sent in re.split(r'(?<=[.!?])\s+', chunk_text.strip()):
            sent = sent.strip()
            if len(sent) > 30:
                s_words = set(re.findall(r'\b[a-z]{3,}\b', sent.lower())) - stop
                sentences.append((len(q_words & s_words), sent))
    sentences.sort(key=lambda x: x[0], reverse=True)
    top = [s for sc, s in sentences[:5] if sc > 0] or [s for _, s in sentences[:3]]
    answer = "Based on the available information:\n\n" + "\n\n".join(f"• {s}" for s in top)
    if sources:
        answer += f"\n\n📄 *Source: {', '.join(sources)}*"
    answer += ("\n\n---\n_⚡ AI summarization temporarily unavailable. "
               "Answer extracted directly from knowledge base._")
    return answer

